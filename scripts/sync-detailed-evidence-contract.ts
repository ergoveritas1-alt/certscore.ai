import { readFile, writeFile } from "node:fs/promises";
import { z } from "zod";
import {
  detailedEvidenceCountsSchema, detailedEvidenceRowSchema, detailedEvidenceSectionSchema,
  detailedEvidenceReportSchema, publicCmpAuditSchema, publicCmsSecuritySchema, consentControlMeasurementSchema,
} from "../packages/certscore-api-contracts/src/detailed-evidence";

/** Standalone SDK types and OpenAPI share the public runtime schemas. */
function project(schema: z.ZodTypeAny): { ts: string; json: any } {
  if (schema instanceof z.ZodEffects) return project(schema.innerType());
  if (schema instanceof z.ZodOptional) return project(schema.unwrap());
  if (schema instanceof z.ZodNullable) { const p = project(schema.unwrap()); return { ts: `${p.ts} | null`, json: { anyOf: [p.json, { type: "null" }] } }; }
  if (schema instanceof z.ZodLiteral) return { ts: JSON.stringify(schema.value), json: { const: schema.value, type: typeof schema.value } };
  if (schema instanceof z.ZodEnum) return { ts: schema.options.map((value: string) => JSON.stringify(value)).join(" | "), json: { type: "string", enum: schema.options } };
  if (schema instanceof z.ZodBoolean) return { ts: "boolean", json: { type: "boolean" } };
  if (schema instanceof z.ZodNumber) return { ts: "number", json: { type: schema.isInt ? "integer" : "number", ...(schema.minValue !== null ? { minimum: schema.minValue } : {}), ...(schema.maxValue !== null ? { maximum: schema.maxValue } : {}) } };
  if (schema instanceof z.ZodString) return { ts: "string", json: { type: "string", ...Object.fromEntries(schema._def.checks.flatMap(c => c.kind === "max" ? [["maxLength", c.value]] : c.kind === "regex" ? [["pattern", c.regex.source]] : c.kind === "url" ? [["format", "uri"]] : [])) } };
  if (schema instanceof z.ZodTuple) {
    const items = schema.items.map((item: z.ZodTypeAny) => project(item));
    return { ts: `[${items.map((item: { ts: string }) => item.ts).join(", ")}]`, json: { type: "array", prefixItems: items.map((item: { json: unknown }) => item.json), minItems: items.length, maxItems: items.length } };
  }
  if (schema instanceof z.ZodArray) { const p = project(schema.element); return { ts: `Array<${p.ts}>`, json: { type: "array", items: p.json, ...(schema._def.maxLength ? { maxItems: schema._def.maxLength.value } : {}), ...(schema._def.exactLength ? { minItems: schema._def.exactLength.value, maxItems: schema._def.exactLength.value } : {}) } }; }
  if (schema instanceof z.ZodObject) {
    const entries = Object.entries(schema.shape).map(([key, value]) => ({ key, optional: (value as z.ZodTypeAny).isOptional(), ...project(value as z.ZodTypeAny) }));
    return { ts: `{ ${entries.map(item => `${item.key}${item.optional ? "?" : ""}: ${item.ts};`).join(" ")} }`, json: { type: "object", additionalProperties: false, required: entries.filter(item => !item.optional).map(item => item.key), properties: Object.fromEntries(entries.map(item => [item.key, item.json])) } };
  }
  throw new Error(`Unsupported detailed evidence schema: ${schema._def.typeName}`);
}
async function main() {
  const schemas = { DetailedEvidenceCounts: detailedEvidenceCountsSchema, DetailedEvidenceRow: detailedEvidenceRowSchema,
    DetailedEvidenceSection: detailedEvidenceSectionSchema, DetailedEvidenceReport: detailedEvidenceReportSchema,
    PublicCmpAudit: publicCmpAuditSchema, PublicCmsSecurity: publicCmsSecuritySchema, ConsentControlMeasurement: consentControlMeasurementSchema };
  const projected = Object.entries(schemas).map(([name, schema]) => [name, project(schema)] as const);
  const banner = "// Generated by scripts/sync-detailed-evidence-contract.ts; do not edit.\n";
  const files = {
    "packages/certscore-sdk/src/detailed-evidence-types.ts": banner + projected.map(([name, p]) => `export type ${name} = ${p.ts};`).join("\n") + "\n",
    "packages/certscore-api-contracts/src/detailed-evidence-openapi.ts": banner + `export const detailedEvidenceOpenApiSchemas = ${JSON.stringify(Object.fromEntries(projected.map(([name, p]) => [name, p.json])), null, 2)} as const;\n`,
  };
  for (const [file, content] of Object.entries(files)) {
    if (process.argv.includes("--check")) { if (await readFile(file, "utf8") !== content) throw new Error(`Generated contract drift: ${file}`); }
    else await writeFile(file, content);
  }
}
void main();
